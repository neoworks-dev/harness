import type { Model, TypeExpr } from "./model.ts";

function doc(description: string | undefined, indent = ""): string {
  if (!description) return "";
  return `${indent}/** ${description.replaceAll("*/", "*\\/")} */\n`;
}

function tsType(t: TypeExpr): string {
  switch (t.kind) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "any":
      return "unknown";
    case "ref":
      return t.name;
    case "array": {
      const inner = tsType(t.items);
      return t.items.kind === "ref" || !inner.includes(" ") ? `${inner}[]` : `(${inner})[]`;
    }
    case "map":
      return `Record<string, ${tsType(t.values)}>`;
  }
}

export function generateTs(model: Model): string {
  let out = "// Code generated by protocol/codegen from protocol/schemas. DO NOT EDIT.\n\n";
  for (const def of model.defs) {
    out += doc(def.description);
    switch (def.kind) {
      case "enum":
        out += `export type ${def.name} = ${def.values.map((v) => JSON.stringify(v)).join(" | ")};\n\n`;
        break;
      case "union":
        out += `export type ${def.name} = ${def.variants.join(" | ")};\n\n`;
        out += `export type ${def.name}Tag = ${def.name}[${JSON.stringify(def.tagField)}];\n\n`;
        break;
      case "object": {
        out += `export interface ${def.name} {\n`;
        if (def.tag) out += `  ${def.tag.field}: ${JSON.stringify(def.tag.value)};\n`;
        for (const f of def.fields) {
          out += doc(f.description, "  ");
          const name = f.required ? f.name : `${f.name}?`;
          out += `  ${name}: ${tsType(f.type)};\n`;
        }
        out += "}\n\n";
        break;
      }
    }
  }
  return out;
}
