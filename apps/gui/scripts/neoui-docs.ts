export interface SceneDoc {
  ask: string;
  before: string;
  program: string;
  after?: string;
  /** The fence is left open, as while the agent is still writing it. */
  streaming?: boolean;
}

const lines = (...parts: string[]): string => parts.join("\n");

/** Cards, stacks and tabs in turn, `levels` deep, with a field at the bottom. */
function deepProgram(levels: number): string {
  const open = (level: number): string => {
    if (level % 3 === 0) return `<Card title="Level ${level}">`;
    if (level % 3 === 1) return `<Stack><Text tone="muted">Level ${level}</Text>`;
    return `<Tabs><Tab label="Level ${level}">`;
  };
  const close = (level: number): string => {
    if (level % 3 === 0) return "</Card>";
    if (level % 3 === 1) return "</Stack>";
    return "</Tab></Tabs>";
  };
  const bottom =
    '<Stack><Text>The bottom.</Text><FormControl label="Deep field"><Input name="deep" placeholder="typed at the bottom"/></FormControl></Stack>';
  const opens = Array.from({ length: levels - 1 }, (_, level) => open(level));
  const closes = Array.from({ length: levels - 1 }, (_, level) => close(level)).reverse();
  return [...opens, bottom, ...closes].join("\n");
}

